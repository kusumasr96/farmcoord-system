// ── Priority calculation helpers (for demo data) ──
function calculateDemoPriority(params: {
  urgencyScore: number;
  weatherScore: number;
  cropScore: number;
  waitingScore: number;
  distanceScore: number;
  constraintScore: number;
  explanation: string;
}): PriorityBreakdown {
  const total =
    params.urgencyScore +
    params.weatherScore +
    params.cropScore +
    params.waitingScore +
    params.distanceScore +
    params.constraintScore;
  return {
    urgency: params.urgencyScore,
    weather: params.weatherScore,
    crop: params.cropScore,
    waiting: params.waitingScore,
    distance: params.distanceScore,
    constraint: params.constraintScore,
    total,
    explanation: params.explanation,
  };
}

